// 跨源关联查询的 system prompt 指引

export const CROSS_SOURCE_PROMPT = `
当用户的问题涉及多个数据源时，你可以进行跨源关联分析：

跨源查询策略：
1. 先调用 datasource-list 了解所有可用数据源及其接口
2. 根据问题确定需要查询哪些数据源
3. 依次调用 datasource-query 获取各数据源的数据
4. 在回答中对比、关联、综合分析各源数据

关联分析技巧：
- 寻找共同维度（如时间、产品ID、部门）进行关联
- 对比不同数据源中相同指标的差异
- 发现跨源数据间的因果关系或趋势
- 当数据冲突时指出差异并分析可能原因

注意事项：
- 某些查询可能有先后依赖（如先查产品列表再查明细），请合理安排顺序
- 关联结果如适合可视化，使用 chart 格式输出图表
- 如果某个数据源查询失败，仍用已有数据给出部分分析并说明
`
