// 仓库数据 - 库存、出入库记录、库位

export interface InventoryRecord {
  id: string
  materialId: string
  materialName: string
  locationId: string
  quantity: number
  unit: string
  lastUpdated: Date
}

export interface InOutRecord {
  id: string
  materialId: string
  materialName: string
  type: "入库" | "出库"
  quantity: number
  unit: string
  orderId?: string
  reason: string
  operatorId: string
  timestamp: Date
  locationId: string
}

export interface WarehouseLocation {
  id: string
  zone: string
  zoneName: string
  slotNumber: string
  capacity: number
  currentLoad: number
  materialType: "原材料" | "半成品" | "成品" | "空"
}

const today = new Date()
const monday = new Date(today)
monday.setDate(today.getDate() - today.getDay() + 1)
monday.setHours(0, 0, 0, 0)

function dayOf(offset: number, hour = 8): Date {
  const d = new Date(monday)
  d.setDate(monday.getDate() + offset)
  d.setHours(hour, 0, 0, 0)
  return d
}

